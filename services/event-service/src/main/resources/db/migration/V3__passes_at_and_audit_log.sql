-- Two additions, both needed by the admin command line (SPEC.md §0.1).

-- 1. The moment an event stops being upcoming.
--
-- The rule (after the end, or after the end of the starting day in
-- Europe/Berlin) lives in exactly one place, Event#computePassesAt in Java. This
-- column stores its output so that a list can filter and paginate in SQL
-- without restating the rule there. It is not a "past" flag and it cannot go
-- stale: it depends only on starts_at and ends_at, which change only through the
-- entity, which recomputes it. The comparison with the current time happens at
-- query time.
ALTER TABLE events ADD COLUMN passes_at timestamptz;

-- One-time transcription of the rule for rows written before this migration.
-- There were none in any environment when it was written; it exists so the
-- migration is correct regardless. The living definition is the Java one.
UPDATE events
SET passes_at = coalesce(
    ends_at,
    ((date_trunc('day', starts_at AT TIME ZONE 'Europe/Berlin') + interval '1 day')
        AT TIME ZONE 'Europe/Berlin')
);

ALTER TABLE events ALTER COLUMN passes_at SET NOT NULL;

-- The upcoming feed and the admin list both ask "published and not yet passed,
-- by date".
CREATE INDEX events_status_passes_at_idx ON events (status, passes_at);

-- 2. The audit log, from the first write path rather than once there are users
-- (SPEC.md §0.1): who, what, on which object, when. Creation, revision,
-- cancellation and deletion of an event are always recorded.
CREATE TABLE audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL DEFAULT now(),

    -- For the command line "who" is the named operator and the account on the
    -- server, not a network address (SPEC.md §0.1).
    operator    text        NOT NULL,
    os_user     text        NOT NULL,
    channel     text        NOT NULL,

    action      text        NOT NULL,
    entity_type text        NOT NULL,

    -- No foreign key on purpose: an entry about a deletion has to outlive the
    -- row it describes. The slug is kept beside the id for the same reason, it is
    -- what a human searches by.
    entity_id   bigint,
    entity_key  text        NOT NULL,

    details     jsonb,

    CONSTRAINT audit_log_channel_known CHECK (channel IN ('CLI', 'PANEL')),
    CONSTRAINT audit_log_action_known CHECK (action IN (
        'EVENT_CREATED', 'EVENT_UPDATED', 'EVENT_CANCELLED', 'EVENT_DELETED'
    )),
    CONSTRAINT audit_log_entity_type_known CHECK (entity_type IN ('EVENT'))
);

CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_key, occurred_at);
