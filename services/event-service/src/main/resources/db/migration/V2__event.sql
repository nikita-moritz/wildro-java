-- The single entity of stage one. SPEC.md §0 and its closed open questions are
-- the authority for every column here; §1 onward is unreviewed draft and nothing
-- from it is reflected.

CREATE TABLE events (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The public address of the event page, and the key the ingestion CLI
    -- upserts on, which is why it is explicit rather than derived: re-importing
    -- a source must update the same row instead of minting a second page.
    slug              text        NOT NULL,

    -- Открытый вопрос 2: an external event is announced elsewhere and we link
    -- out to it; an own event is ours. Stage one knows only external ones, but
    -- the distinction decides whether a source link is mandatory, so it is a
    -- column rather than an assumption.
    kind              text        NOT NULL,
    status            text        NOT NULL,

    activity_type     text        NOT NULL,
    difficulty        text,

    starts_at         timestamptz NOT NULL,
    ends_at           timestamptz,

    -- SPEC.md §0: no start coordinates, no event. The filter, the search, the
    -- map and the city pages all rest on this, so it is NOT NULL in the schema
    -- and not only in a form check. geography rather than geometry: distances
    -- come out in metres on the sphere, which is what "within 30 km of me"
    -- means, instead of in degrees.
    start_point       geography(Point, 4326) NOT NULL,

    -- Plain text out of the source, never an account: there are no user
    -- accounts and none are planned for stage one.
    organizer         text        NOT NULL,

    source_url        text,
    -- The page of an external event permanently carries "data from the source,
    -- check the link" together with this date. We cannot guarantee freshness and
    -- pretending otherwise would be dishonest.
    source_checked_at timestamptz,

    distance_km       numeric(6, 2),
    elevation_gain_m  integer,

    -- Открытый вопрос 2: the field lives in the model for own events and future
    -- booking, and is never shown for an external one. Wiring a booking limit to
    -- a number scraped from someone's chat would have us turning people away on
    -- the strength of a year-old message.
    max_participants  integer,

    cover_image_url   text,

    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT events_slug_unique UNIQUE (slug),

    -- Enumerations are held as text with a check rather than as PostgreSQL enum
    -- types. Both give the same guarantee; only one of them lets a value be
    -- removed or renamed without rewriting the type and everything depending on
    -- it. The Java enum is the source of truth, this list mirrors it.
    CONSTRAINT events_kind_known CHECK (kind IN ('EXTERNAL', 'OWN')),
    CONSTRAINT events_status_known CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    CONSTRAINT events_activity_type_known CHECK (activity_type IN (
        'HIKING', 'TRAIL_RUN', 'CYCLING', 'WATER', 'MOUNTAINEERING',
        'CLIMBING', 'FERRATA', 'KIDS', 'YOGA', 'CAMPING'
    )),
    CONSTRAINT events_difficulty_known CHECK (difficulty IS NULL OR difficulty IN ('EASY', 'MEDIUM', 'HARD')),

    -- An external event without a link out is not an external event: the link is
    -- the attribution and the only place the visitor can sign up.
    CONSTRAINT events_external_has_source CHECK (kind <> 'EXTERNAL' OR source_url IS NOT NULL),
    CONSTRAINT events_ends_after_start CHECK (ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT events_distance_positive CHECK (distance_km IS NULL OR distance_km > 0),
    CONSTRAINT events_elevation_not_negative CHECK (elevation_gain_m IS NULL OR elevation_gain_m >= 0),
    CONSTRAINT events_capacity_positive CHECK (max_participants IS NULL OR max_participants > 0)
);

-- Proximity is a database query, not application arithmetic (SPEC.md §0.3), and
-- the map answers per visible bounding box. Both are this index.
CREATE INDEX events_start_point_idx ON events USING gist (start_point);

-- The base feed is upcoming events ordered by date, narrowed by status. Ordering
-- and filtering share one index so the feed does not sort a full table.
CREATE INDEX events_status_starts_at_idx ON events (status, starts_at);

-- The filtered lists narrow by activity type before ordering by date.
CREATE INDEX events_activity_type_starts_at_idx ON events (activity_type, starts_at);

-- Every translated string of an event. A separate table rather than columns per
-- language: three languages are a house rule today and the count is not a schema
-- decision worth repeating in every future entity.
--
-- The place in words lives here with the name and the description because a card
-- must not mix languages. The working version showed an English date beside a
-- Russian country name, which is exactly the defect SPEC.md §0 calls out.
CREATE TABLE event_translations (
    event_id    bigint NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    locale      text   NOT NULL,
    name        text   NOT NULL,
    place_name  text   NOT NULL,

    -- Written in our own words. Copying the source is a duplicate in the eyes of
    -- a search engine and someone else's text besides (SPEC.md §0.3).
    description text   NOT NULL,

    PRIMARY KEY (event_id, locale),
    CONSTRAINT event_translations_locale_known CHECK (locale IN ('de', 'en', 'ru')),
    CONSTRAINT event_translations_name_not_blank CHECK (length(btrim(name)) > 0),
    CONSTRAINT event_translations_place_not_blank CHECK (length(btrim(place_name)) > 0),
    CONSTRAINT event_translations_description_not_blank CHECK (length(btrim(description)) > 0)
);
